import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import { AGENT, FakeSys, ROOT, capture } from './fake.test.ts';
import { idProblem, reviewThread, threadArgs, withoutFooter } from './review-thread.ts';

const THREAD = 'PRRT_kwDOabc123';
const COMMENT = 'PRRC_kwDOfirst';
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';

type Page = { nodes: { id: string; body: string }[]; pageInfo: { hasNextPage: boolean; endCursor?: string | null } };

/**
 * An agent session, with GitHub showing THREAD on pull request #40 of this repository; its comments come in
 * `pages`, one per request, the first unless a cursor asks for a later one.
 */
function session(pull: Record<string, unknown> = {}, isResolved = false, pages: Page[] = [{ nodes: [{ id: COMMENT, body: 'Use a constant.' }], pageInfo: { hasNextPage: false } }]): FakeSys {
  const sys = new FakeSys();
  sys.env = { NIYAM_AGENT: AGENT, GH_TOKEN: 'ghp_good' };
  sys.acceptToken('ghp_good', AGENT);
  sys.route('POST', '/graphql', () => {
    const { query, variables } = sys.requests.at(-1)?.body as { query: string; variables: { after?: string } };
    if (query.startsWith('query')) {
      const page = variables.after === undefined ? 0 : Number(variables.after.replace('c', ''));
      return {
        status: 200,
        json: { data: { node: { isResolved, pullRequest: { number: 40, author: { login: AGENT }, repository: { nameWithOwner: 'example-org/example-app' }, ...pull }, comments: pages[page] } } },
      };
    }
    return { status: 200, json: { data: { done: true } } };
  });
  return sys;
}

async function run(sys: FakeSys, args: string[]): Promise<{ code: number; out: string[]; err: string[] }> {
  const { io, out, err } = capture();
  return { code: await reviewThread(sys, io, args), out, err };
}

const mutations = (sys: FakeSys): { query: string; variables: Record<string, string> }[] =>
  sys.requests.flatMap((r) => (r.url.endsWith('/graphql') && (r.body as { query: string }).query.startsWith('mutation') ? [r.body as { query: string; variables: Record<string, string> }] : []));

describe('threadArgs', () => {
  it('reads a thread id with a reply, resolve, or both', () => {
    assert.deepEqual(threadArgs([THREAD, '--reply', 'Fixed.', '--resolve']), { thread: THREAD, reply: 'Fixed.', resolve: true });
    assert.deepEqual(threadArgs([THREAD, '--resolve']), { thread: THREAD, resolve: true });
    assert.deepEqual(threadArgs(['123', '--reply', 'Fixed.']), { thread: '123', reply: 'Fixed.', resolve: false });
  });

  it('resolves with a reply from a file, unless told not to', () => {
    assert.deepEqual(threadArgs([THREAD, '--body-file', 'reply.md']), { thread: THREAD, bodyFile: 'reply.md', resolve: true });
    assert.deepEqual(threadArgs([THREAD, '--body-file', 'reply.md', '--no-resolve']), { thread: THREAD, bodyFile: 'reply.md', resolve: false });
    assert.deepEqual(threadArgs([THREAD, '--body-file', 'reply.md', '--resolve']), { thread: THREAD, bodyFile: 'reply.md', resolve: true });
  });

  it('reads a reaction with the comment it goes on', () => {
    assert.deepEqual(threadArgs([THREAD, '--reaction', '+1', '--comment-id', COMMENT]), { thread: THREAD, resolve: false, reaction: '+1', comment: COMMENT });
    assert.deepEqual(threadArgs([THREAD, '--comment-id', COMMENT, '--reaction', '-1', '--resolve']), { thread: THREAD, resolve: true, reaction: '-1', comment: COMMENT });
  });

  for (const [args, message] of [
    [[], /needs a review thread id \(PRRT_…, or in a Claude cloud session its first comment's number\)$/],
    [['12x'], /needs a review thread id \(PRRT_…, or in a Claude cloud session its first comment's number\), not "12x"$/],
    [['012', '--resolve'], /not "012"$/],
    [[THREAD], /needs --reply <text>, --body-file <path>, --resolve, or --reaction/],
    [[THREAD, '--reply'], /--reply needs the text of the reply/],
    [[THREAD, '--reply', ' '], /--reply needs the text of the reply/],
    [[THREAD, '--reply', '--resolve'], /--reply needs the text of the reply/],
    [[THREAD, '--reply', 'a', '--reply', 'b'], /unexpected argument "--reply"/],
    [[THREAD, '--resolve', '--resolve'], /unexpected argument "--resolve"/],
    [[THREAD, '--delete'], /unexpected argument "--delete"/],
    [[THREAD, '--body-file'], /--body-file needs a value/],
    [[THREAD, '--reply', 'a', '--body-file', 'b'], /takes --reply or --body-file, not both/],
    [[THREAD, '--body-file', 'b', '--resolve', '--no-resolve'], /takes --resolve or --no-resolve, not both/],
    [[THREAD, '--reply', 'a', '--no-resolve'], /--no-resolve goes with --body-file/],
    [[THREAD, '--reaction', 'rocket', '--comment-id', COMMENT], /--reaction takes \+1 or -1, not "rocket"/],
    [[THREAD, '--reaction', 'constructor', '--comment-id', COMMENT], /--reaction takes \+1 or -1/],
    [[THREAD, '--reaction', '+1'], /--reaction and --comment-id go together/],
    [[THREAD, '--comment-id', COMMENT, '--resolve'], /--reaction and --comment-id go together/],
  ] as const) {
    it(`refuses ${JSON.stringify(args)}`, () => {
      assert.throws(() => threadArgs(args), message);
    });
  }
});

describe('reviewThread', () => {
  it("replies on, then resolves, a thread on the agent's own pull request", async () => {
    const sys = session();
    assert.deepEqual(await run(sys, [THREAD, '--reply', 'Fixed in abc123.', '--resolve']), {
      code: 0,
      out: [`✓ replied on ${THREAD} (#40)`, `✓ resolved ${THREAD} (#40)`],
      err: [],
    });
    const [reply, resolve] = mutations(sys);
    assert.match(reply?.query ?? '', /addPullRequestReviewThreadReply/);
    assert.deepEqual(reply?.variables, { id: THREAD, body: 'Fixed in abc123.' });
    assert.match(resolve?.query ?? '', /resolveReviewThread/);
    assert.ok(sys.requests.every((r) => r.token === 'ghp_good'));
  });

  it('only replies, or only resolves, as asked', async () => {
    const replied = session();
    assert.deepEqual((await run(replied, [THREAD, '--reply', 'Not changed: the reason.'])).out, [`✓ replied on ${THREAD} (#40)`]);
    assert.equal(mutations(replied).length, 1);
    const resolved = session();
    assert.deepEqual((await run(resolved, [THREAD, '--resolve'])).out, [`✓ resolved ${THREAD} (#40)`]);
  });

  it('leaves a resolved thread be', async () => {
    const sys = session({}, true);
    assert.deepEqual((await run(sys, [THREAD, '--resolve'])).out, [`✓ ${THREAD} (#40) was already resolved`]);
    assert.equal(mutations(sys).length, 0);
  });

  for (const [name, pull, problem] of [
    ['another account opened', { author: { login: 'example-owner' } }, `${THREAD} is on #40, which example-owner opened, not ${AGENT}`],
    ['a deleted account opened', { author: null }, `${THREAD} is on #40, which a deleted account opened, not ${AGENT}`],
    ['another repository has', { repository: { nameWithOwner: 'other-org/other-app' } }, `${THREAD} is on other-org/other-app#40, not a pull request in example-org/example-app`],
  ] as const) {
    it(`refuses a thread on a pull request ${name}`, async () => {
      const sys = session(pull);
      assert.deepEqual(await run(sys, [THREAD, '--resolve']), { code: 1, out: [], err: [`✗ ${problem}`, 'review-thread: refused'] });
      assert.equal(mutations(sys).length, 0);
    });
  }

  it('refuses an id that is not a review thread', async () => {
    const sys = session();
    sys.route('POST', '/graphql', { status: 200, json: { data: { node: null } } });
    assert.deepEqual((await run(sys, [THREAD, '--resolve'])).err, [`✗ ${THREAD} is not a review thread GitHub shows ${AGENT}`, 'review-thread: refused']);
  });

  it("refuses a token that is not the agent's, and a session with none", async () => {
    const owner = session();
    owner.env.GH_TOKEN = 'ghp_owner';
    owner.acceptToken('ghp_owner', 'example-owner');
    assert.deepEqual((await run(owner, [THREAD, '--resolve'])).err, [`✗ review-thread answers as ${AGENT}, but this session's token is example-owner`, 'review-thread: refused']);
    const refused = session();
    refused.env.GH_TOKEN = 'ghp_unknown';
    assert.match((await run(refused, [THREAD, '--resolve'])).err[0] ?? '', /this session's token is refused$/);
    const none = session();
    delete none.env.GH_TOKEN;
    assert.deepEqual((await run(none, [THREAD, '--resolve'])).err, ['✗ this session has no token; run niyam doctor', 'review-thread: refused']);
    assert.equal(owner.requests.filter((r) => r.url.endsWith('/graphql')).length, 0);
  });

  it('with two agents, answers as either on a pull request either opened, and refuses an owner', async () => {
    const team = (login: string, author: string): FakeSys => {
      const sys = session({ author: { login: author } });
      sys.files.set(`${ROOT}/.github/niyam.json`, JSON.stringify({ owner: ['example-owner', 'Second-Owner'], agent: [AGENT, 'OtherBot'] }));
      sys.acceptToken('ghp_good', login);
      return sys;
    };
    assert.equal((await run(team('OtherBot', AGENT), [THREAD, '--resolve'])).code, 0);
    assert.equal((await run(team(AGENT, 'otherbot'), [THREAD, '--resolve'])).code, 0);
    assert.deepEqual((await run(team('OtherBot', 'Second-Owner'), [THREAD, '--resolve'])).err, [
      `✗ ${THREAD} is on #40, which Second-Owner opened, not ${AGENT} or OtherBot`,
      'review-thread: refused',
    ]);
    assert.deepEqual((await run(team('Second-Owner', AGENT), [THREAD, '--resolve'])).err, [
      `✗ review-thread answers as ${AGENT} or OtherBot, but this session's token is Second-Owner`,
      'review-thread: refused',
    ]);
  });

  it('throws when GitHub refuses, naming what it refused', async () => {
    const forbidden = session();
    forbidden.route('POST', '/graphql', { status: 403, json: null });
    await assert.rejects(run(forbidden, [THREAD, '--resolve']), /GitHub refused to read review thread PRRT_kwDOabc123 \(HTTP 403\)/);
    const errors = session();
    errors.route('POST', '/graphql', { status: 200, json: { data: null, errors: [{ message: 'Resource not accessible by integration' }] } });
    await assert.rejects(run(errors, [THREAD, '--resolve']), /\(HTTP 200: Resource not accessible by integration\)/);
  });

  it('replies from a file and resolves, reading the file from the working directory', async () => {
    const sys = session();
    sys.files.set(`${ROOT}/reply.md`, '\nFixed in `abc123`: the {limit} is a constant now.\n');
    assert.deepEqual(await run(sys, [THREAD, '--body-file', 'reply.md']), { code: 0, out: [`✓ replied on ${THREAD} (#40)`, `✓ resolved ${THREAD} (#40)`], err: [] });
    assert.deepEqual(mutations(sys)[0]?.variables, { id: THREAD, body: 'Fixed in `abc123`: the {limit} is a constant now.' });
    const absolute = session();
    absolute.files.set('/elsewhere/reply.md', 'Not changed: the reason.');
    assert.equal((await run(absolute, [THREAD, '--body-file', '/elsewhere/reply.md', '--no-resolve'])).code, 0);
    assert.equal(mutations(absolute).length, 1);
  });

  it('refuses a reply file that is missing or empty, before any request', async () => {
    const missing = session();
    assert.deepEqual((await run(missing, [THREAD, '--body-file', 'reply.md'])).err, ['✗ reply.md is not there', 'review-thread: refused']);
    const empty = session();
    empty.files.set(`${ROOT}/reply.md`, '  \n');
    assert.deepEqual((await run(empty, [THREAD, '--body-file', 'reply.md'])).err, ['✗ reply.md is empty: there is no reply in it', 'review-thread: refused']);
    assert.equal(missing.requests.length + empty.requests.length, 0);
  });

  it('never posts the same reply twice, looking through every page of the thread', async () => {
    const pages: Page[] = [
      { nodes: [{ id: COMMENT, body: 'Use a constant.' }], pageInfo: { hasNextPage: true, endCursor: 'c1' } },
      { nodes: [{ id: 'PRRC_kwDOreply', body: '  Fixed in abc123.\n' }], pageInfo: { hasNextPage: false } },
    ];
    const sys = session({}, false, pages);
    assert.deepEqual(await run(sys, [THREAD, '--reply', 'Fixed in abc123.', '--resolve']), {
      code: 0,
      out: [`✓ ${THREAD} (#40) has this reply already`, `✓ resolved ${THREAD} (#40)`],
      err: [],
    });
    assert.deepEqual(
      mutations(sys).map((m) => m.query.match(/(\w+)\(input/)?.[1]),
      ['resolveReviewThread'],
    );
  });

  it('refuses a page of comments that says more follow but gives no cursor, posting nothing', async () => {
    const sys = session({}, false, [{ nodes: [], pageInfo: { hasNextPage: true, endCursor: null } }]);
    await assert.rejects(run(sys, [THREAD, '--reply', 'Fixed.']), /a page says more follow but gives no cursor/);
    assert.equal(mutations(sys).length, 0);
  });

  it("reacts on one of the thread's comments, and still resolves when the reaction fails", async () => {
    const sys = session();
    assert.deepEqual(await run(sys, [THREAD, '--reaction', '+1', '--comment-id', COMMENT, '--resolve']), {
      code: 0,
      out: [`✓ reacted +1 on ${COMMENT}`, `✓ resolved ${THREAD} (#40)`],
      err: [],
    });
    assert.deepEqual(mutations(sys)[0]?.variables, { id: COMMENT, content: 'THUMBS_UP' });
    const failing = session();
    failing.route('POST', '/graphql', () => {
      const { query } = failing.requests.at(-1)?.body as { query: string };
      if (query.includes('addReaction')) return { status: 403, json: null };
      return query.startsWith('query')
        ? { status: 200, json: { data: { node: { isResolved: false, pullRequest: { number: 40, author: { login: AGENT }, repository: { nameWithOwner: 'example-org/example-app' } }, comments: { nodes: [{ id: COMMENT, body: 'x' }], pageInfo: { hasNextPage: false } } } } } }
        : { status: 200, json: { data: { done: true } } };
    });
    const result = await run(failing, [THREAD, '--reaction', '-1', '--comment-id', COMMENT, '--resolve']);
    assert.deepEqual(result.out, [`✓ resolved ${THREAD} (#40)`]);
    assert.match(result.err[0] ?? '', /^⚠ the -1 on PRRC_kwDOfirst failed \(GitHub refused to react on PRRC_kwDOfirst \(HTTP 403\)\); going on$/);
  });

  it('refuses a reaction on a comment that is not in the thread', async () => {
    const sys = session();
    assert.deepEqual((await run(sys, [THREAD, '--reaction', '+1', '--comment-id', 'PRRC_kwDOelse'])).err, [`✗ PRRC_kwDOelse is not a comment of ${THREAD}`, 'review-thread: refused']);
    assert.equal(mutations(sys).length, 0);
  });

  it('refuses a cloud thread id on this machine, before any request', async () => {
    const sys = session();
    assert.deepEqual((await run(sys, ['123', '--resolve'])).err, [
      '✗ on this machine a thread is named by its node id (PRRT_…), as pr-signals prints it, not the number 123',
      'review-thread: refused',
    ]);
    assert.equal(sys.requests.length, 0);
  });
});

describe('idProblem', () => {
  it('takes node ids on a machine and numbers in a Claude cloud session', () => {
    assert.equal(idProblem(false, THREAD, COMMENT), undefined);
    assert.equal(idProblem(false, THREAD), undefined);
    assert.equal(idProblem(true, '123', '456'), undefined);
    assert.equal(idProblem(true, '123'), undefined);
  });

  for (const [cloud, thread, comment, message] of [
    [false, '123', undefined, /not the number 123$/],
    [false, THREAD, '456', /--comment-id takes a comment's node id, as pr-signals prints it, not 456$/],
    [false, THREAD, THREAD, /--comment-id takes a comment's node id, as pr-signals prints it, not PRRT_kwDOabc123$/],
    [false, THREAD, 'plain', /not plain$/],
    [true, THREAD, undefined, /its first comment's number \(the one in its #discussion_r link, or the thread pr-signals prints there\), not PRRT_kwDOabc123$/],
    [true, '123', COMMENT, /in a Claude cloud session --comment-id takes a comment's number, not PRRC_kwDOfirst$/],
  ] as const) {
    it(`refuses ${thread} ${comment ?? ''} ${cloud ? 'in the cloud' : 'on a machine'}`, () => {
      assert.match(idProblem(cloud, thread, comment) ?? '', message);
    });
  }
});

describe('withoutFooter', () => {
  it("takes off the cloud proxy's footer, with or without a session path, and nothing else", () => {
    assert.equal(withoutFooter(`Fixed.${FOOTER}`), 'Fixed.');
    assert.equal(withoutFooter('Fixed.\n---\n_Generated by [Claude Code](https://claude.ai/code/session_1)_\n'), 'Fixed.');
    assert.equal(withoutFooter('Fixed.\n---\n_Generated by someone else_'), 'Fixed.\n---\n_Generated by someone else_');
  });
});

const REPO = '/repos/example-org/example-app';

/** A Claude cloud session, with comment 123 opening a thread on #40 and 124 replying in it. */
function cloud(options: { author?: string; inReplyTo?: number | null; resolved?: boolean; replies?: string[]; comment?: number; repository?: string } = {}): FakeSys {
  const sys = new FakeSys();
  sys.env = { NIYAM_AGENT: AGENT, GH_TOKEN: 'ghp_good', CLAUDE_CODE_REMOTE: 'true' };
  sys.acceptToken('ghp_good', AGENT);
  const repository = options.repository ?? 'example-org/example-app';
  sys.route('GET', `${REPO}/pulls/comments/123`, {
    status: options.comment ?? 200,
    json: options.comment === undefined ? { pull_request_url: `https://api.github.com/repos/${repository}/pulls/40`, in_reply_to_id: options.inReplyTo ?? null } : { message: 'Not Found' },
  });
  sys.route('GET', `/repos/${repository}/pulls/40`, { status: 200, json: { user: { login: options.author ?? AGENT } } });
  sys.route('GET', `/repos/${repository}/pulls/40/comments?per_page=100&page=1`, {
    status: 200,
    json: [
      { id: 123, body: 'Use a constant.', user: { login: 'review-bot[bot]' }, path: 'src/a.ts', line: 3 },
      ...(options.replies ?? []).map((body, i) => ({ id: 124 + i, in_reply_to_id: 123, body })),
      { id: 999, body: 'Another thread.' },
    ],
  });
  sys.route('GET', `/repos/${repository}/pulls/40/ccr/review_threads`, { status: 200, json: [{ resolved: options.resolved ?? false, comment_ids: [123, 124] }] });
  sys.route('POST', `${REPO}/pulls/40/comments/123/replies`, { status: 201, json: { id: 200 } });
  sys.route('POST', `${REPO}/pulls/comments/123/reactions`, { status: 201, json: { content: '+1' } });
  sys.route('POST', `${REPO}/pulls/40/ccr/comments/123/resolve`, { status: 200, json: { comment_ids: [123], resolved: true } });
  return sys;
}

const posts = (sys: FakeSys): string[] => sys.requests.filter((r) => r.method === 'POST').map((r) => `${r.url.replace(`https://api.github.com${REPO}/`, '')} ${JSON.stringify(r.body ?? null)}`);

describe('reviewThread in a Claude cloud session', () => {
  it("replies, reacts and resolves over the proxy's REST routes, as the agent", async () => {
    const sys = cloud();
    assert.deepEqual(await run(sys, ['123', '--reply', 'Fixed in abc123.', '--reaction', '+1', '--comment-id', '123', '--resolve']), {
      code: 0,
      out: ['✓ replied on 123 (#40)', '✓ reacted +1 on 123', '✓ resolved 123 (#40)'],
      err: [],
    });
    assert.deepEqual(posts(sys), ['pulls/40/comments/123/replies {"body":"Fixed in abc123."}', 'pulls/comments/123/reactions {"content":"+1"}', 'pulls/40/ccr/comments/123/resolve null']);
    assert.ok(sys.requests.every((r) => !r.url.endsWith('/graphql')));
  });

  it("does not post a reply again that is there with the proxy's footer", async () => {
    const sys = cloud({ replies: [`Fixed in abc123.${FOOTER}`] });
    assert.deepEqual((await run(sys, ['123', '--reply', 'Fixed in abc123.'])).out, ['✓ 123 (#40) has this reply already']);
    assert.deepEqual(posts(sys), []);
  });

  it('leaves a resolved thread be', async () => {
    const sys = cloud({ resolved: true });
    assert.deepEqual((await run(sys, ['123', '--resolve'])).out, ['✓ 123 (#40) was already resolved']);
    assert.deepEqual(posts(sys), []);
  });

  for (const [name, options, args, problem] of [
    ['a reply named as a thread', { inReplyTo: 120 }, ['123', '--resolve'], '123 is a reply, not the first comment of its thread; name the thread by its first comment, as pr-signals prints it'],
    ['a comment GitHub does not show', { comment: 404 }, ['123', '--resolve'], '123 is not a review comment in example-org/example-app'],
    ['a thread on a pull request another account opened', { author: 'example-owner' }, ['123', '--resolve'], '123 is on #40, which example-owner opened, not ExampleBot'],
    ['a thread in another repository', { repository: 'other-org/other-app' }, ['123', '--resolve'], '123 is on other-org/other-app#40, not a pull request in example-org/example-app'],
    ['a reaction on a comment of another thread', {}, ['123', '--reaction', '+1', '--comment-id', '999'], '999 is not a comment of 123'],
    ['a node id', {}, [THREAD, '--resolve'], "in a Claude cloud session a thread is named by its first comment's number (the one in its #discussion_r link, or the thread pr-signals prints there), not PRRT_kwDOabc123"],
  ] as const) {
    it(`refuses ${name}, posting nothing`, async () => {
      const sys = cloud(options);
      assert.deepEqual(await run(sys, [...args]), { code: 1, out: [], err: [`✗ ${problem}`, 'review-thread: refused'] });
      assert.deepEqual(posts(sys), []);
    });
  }

  it('throws when GitHub cannot be read or the proxy does not resolve', async () => {
    const broken = cloud();
    broken.route('GET', `${REPO}/pulls/comments/123`, { status: 500, json: null });
    await assert.rejects(run(broken, ['123', '--resolve']), /cannot read review comment 123 \(HTTP 500\)/);
    const noPull = cloud();
    noPull.route('GET', `${REPO}/pulls/40`, { status: 502, json: null });
    await assert.rejects(run(noPull, ['123', '--resolve']), /cannot read pull request #40 \(HTTP 502\)/);
    const unresolved = cloud();
    unresolved.route('POST', `${REPO}/pulls/40/ccr/comments/123/resolve`, { status: 200, json: { resolved: false } });
    await assert.rejects(run(unresolved, ['123', '--resolve']), /GitHub's proxy did not resolve 123/);
    const refused = cloud();
    refused.route('POST', `${REPO}/pulls/40/comments/123/replies`, { status: 403, json: null });
    await assert.rejects(run(refused, ['123', '--reply', 'x']), /GitHub refused to reply on 123 \(HTTP 403\)/);
  });
});
